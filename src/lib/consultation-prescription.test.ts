import { describe, it, expect } from "vitest";
import { ageOn, parsePrescriptionText } from "./consultation-prescription";
import { isSignedPdf } from "../../supabase/functions/_shared/signed-pdf";

describe("consultation prescription", () => {
  it("turns each non-empty line into an item, removing numbering and bullets", () => {
    const items = parsePrescriptionText("1. Óleo CBD 20% — 5 gotas à noite\n\n- Retorno em 30 dias\n2) Dieta leve");
    expect(items.map((i) => i.name)).toEqual(["Óleo CBD 20% — 5 gotas à noite", "Retorno em 30 dias", "Dieta leve"]);
  });
  it("returns no items for blank text", () => {
    expect(parsePrescriptionText("  \n \n")).toEqual([]);
  });
  it("computes age in full years and tolerates unknown birth dates", () => {
    expect(ageOn("1986-11-13", new Date("2026-11-12T12:00:00"))).toBe(39);
    expect(ageOn("1986-11-12", new Date("2026-11-12T12:00:00"))).toBe(40);
    expect(ageOn(null)).toBe(0);
    expect(ageOn("invalid")).toBe(0);
  });
});

describe("signed PDF upload check", () => {
  const signed = "%PDF-1.7 ... /Type /Sig /Filter /Adobe.PPKLite /ByteRange [0 100 200 300] ...";
  it("accepts a PDF that carries a signature dictionary", () => {
    expect(isSignedPdf("%PDF-", signed, 1000)).toBe(true);
  });
  it("rejects the unsigned PDF generated by the platform", () => {
    expect(isSignedPdf("%PDF-", "%PDF-1.3 ... /Type /Page ...", 1000)).toBe(false);
  });
  it("rejects non-PDF files and files above 10 MB", () => {
    expect(isSignedPdf("\x89PNG\r", signed, 1000)).toBe(false);
    expect(isSignedPdf("%PDF-", signed, 11 * 1024 * 1024)).toBe(false);
  });
});
