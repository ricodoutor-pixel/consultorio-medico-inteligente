// Regras:
//  • Sempre áudio: idoso, intent=pay, intent=sexual (corte seco), pessoa pediu áudio
//  • Sempre áudio: resposta > 400 chars
//  • Texto: 22h-7h (não acordar ninguém), saudações curtas, links puros, profissionais/B2B
