export const resolveProductImg = (url: string | null | undefined): string => {
  if (!url) return oleoCbd1;
  if (url.startsWith("http://") || url.startsWith("https://") || url.startsWith("data:")) return url;
  if (productImagesMap[url]) return productImagesMap[url];

  const filename = url.split("/").pop() || "";
  if (productImagesMap[filename]) return productImagesMap[filename];

  // Try matching by base name
  for (const [key, value] of Object.entries(productImagesMap)) {
    if (key.includes(filename) || filename.includes(key.replace("/src/assets/products/", ""))) {
      return value;
    }
  }

  return url;
};
